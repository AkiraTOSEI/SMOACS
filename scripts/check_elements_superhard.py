#!/usr/bin/env python3
import argparse
import ast
from pathlib import Path

import pandas as pd


DEFAULT_ALLOWED = ["B", "C", "N", "O", "H", "Al", "Si"]


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Check that elements in result.csv stay within allowed set."
    )
    parser.add_argument(
        "--result_csv",
        required=True,
        help="Path to result.csv generated by main.py",
    )
    parser.add_argument(
        "--allowed",
        nargs="+",
        default=DEFAULT_ALLOWED,
        help="Allowed element symbols (space-separated).",
    )
    args = parser.parse_args()

    result_csv = Path(args.result_csv).expanduser().resolve()
    if not result_csv.exists():
        raise SystemExit(f"--result_csv does not exist: {result_csv}")

    df = pd.read_csv(result_csv)
    if "elements_cmn" not in df.columns:
        raise SystemExit("elements_cmn column not found in result.csv")

    allowed = set(args.allowed)
    found = set()
    non_allowed = set()
    for raw in df["elements_cmn"]:
        try:
            elems = ast.literal_eval(raw)
        except Exception:
            elems = []
        for elem in elems:
            found.add(elem)
            if elem not in allowed:
                non_allowed.add(elem)

    print("found_elements:", sorted(found))
    if non_allowed:
        print("non_allowed_elements:", sorted(non_allowed))
        return 1

    print("non_allowed_elements: []")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
